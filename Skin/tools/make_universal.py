# Visibility helpers ----------------------------------------------------------------------------
NO_OVERLAY = "string.equals(#MyTorrents.FolderBrowser.Visible,no)+string.equals(#MyTorrents.TorrentDetails.Visible,no)+string.equals(#MyTorrents.SeriesInfo,no)"
DETAILS = "string.equals(#MyTorrents.TorrentDetails.Visible,yes)"
FOLDERS = "string.equals(#MyTorrents.FolderBrowser.Visible,yes)"
SERIES = "string.equals(#MyTorrents.SeriesInfo,yes)"
FADE = '<animation effect="fade" time="200">WindowOpen</animation><animation effect="fade" time="150">WindowClose</animation>'


def image(x, y, w, h, tex, vis=None, diffuse=None, keep=False, desc="image"):
    v = f"<visible>{vis}</visible>" if vis else ""
    d = f"<colordiffuse>{diffuse}</colordiffuse>" if diffuse else ""
    k = "<keepaspectratio>yes</keepaspectratio><centered>yes</centered>" if keep else ""
    return f"""    <control><description>{desc}</description><type>image</type><id>0</id>
      <posX>{x}</posX><posY>{y}</posY><width>{w}</width><height>{h}</height><texture>{tex}</texture>{d}{k}{v}</control>"""


def label(x, y, w, text, font="font12", color="ffffffff", align="left", vis=None, fade=False, desc="label"):
    v = f"<visible>{vis}</visible>" if vis else ""
    t = "fadelabel" if fade else "label"
    return f"""    <control><description>{desc}</description><type>{t}</type><id>0</id>
      <posX>{x}</posX><posY>{y}</posY><width>{w}</width><label>{text}</label><font>{font}</font><textcolor>{color}</textcolor><align>{align}</align>{v}</control>"""


def button(cid, x, y, w, h, text, up, down, left, right, vis=None, ctype="button", desc="button"):
    v = f"<visible>{vis}</visible>" if vis else ""
    return f"""    <control><description>{desc}</description><type>{ctype}</type><id>{cid}</id>
      <posX>{x}</posX><posY>{y}</posY><width>{w}</width><height>{h}</height><label>{text}</label>
      <onup>{up}</onup><ondown>{down}</ondown><onleft>{left}</onleft><onright>{right}</onright>{v}</control>"""


def window(wid, default, body, extra=""):
    return f"""<?xml version="1.0" encoding="utf-8"?>
{MARK}
<window>
  <id>{wid}</id>
  <defaultcontrol>{default}</defaultcontrol>
  <allowoverlay>yes</allowoverlay>
  <disabletopbar>no</disabletopbar>{extra}
  <define>#header.label:My Torrents</define>
  <controls>
{body}
  </controls>
</window>
"""


def include(body):
    return f"""<?xml version="1.0" encoding="utf-8"?>
{MARK}
<window>
  <controls>
{body}
  </controls>
</window>
"""


