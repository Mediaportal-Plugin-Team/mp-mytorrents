SCALE_TAGS = ("posX", "posY", "width", "height", "textXOff", "textXOff2", "textXOff3", "textYOff", "itemHeight", "spinPosX", "spinPosY")


def scale(xml, f):
    def rep(m):
        return f"<{m.group(1)}>{round(int(m.group(2)) * f)}</{m.group(1)}>"
    return re.sub(r"<(%s)>(-?\d+)</\1>" % "|".join(SCALE_TAGS), rep, xml)


for res, factor in (("1080", 1.0), ("720", 2 / 3)):
    d = os.path.join(OUT, res)
    os.makedirs(d, exist_ok=True)
    for name, fn in FILES.items():
        xml = fn()
        if factor != 1.0:
            xml = scale(xml, factor)
        with open(os.path.join(d, name), "w", encoding="utf-8") as fh:
            fh.write(xml)
print("universal screens written:", ", ".join(FILES))
