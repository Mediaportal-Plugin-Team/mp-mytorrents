"""
Generates the MyTorrents *universal* skin screens - they work in any MediaPortal 1 skin.

  python Skin/tools/make_universal.py

Writes Skin/Universal/1080/*.xml (designed at 1920x1080) and Skin/Universal/720/*.xml (scaled to 1280x720).

Rules that keep them universal:
  * no <import> of skin files, no skin textures - only our own images (mytorrents_universal_*.png/jpg)
  * buttons, lists and checkboxes have no textures/fonts set, so each skin's references.xml supplies its own look
  * only fonts every skin defines: font10, font12, font14
The plugin copies these into any skin that has no MyTorrents screens of its own (see SkinSetup.cs).
"""
import os, re

